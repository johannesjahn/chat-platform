// Reports what a cold load has to fetch before hydration (issue #604): the
// client entry chunk plus every chunk it statically imports (dynamic
// `import()` targets — lazy routes and shell pieces — don't count), and
// which packages/source files make up the entry chunk itself, attributed
// byte-by-byte through its sourcemap. Run from `web/` with
// `bun run analyze`, which builds with sourcemaps first; dependency-free so
// it doesn't drag a visualizer (and a lockfile change) into the project.
import { readdirSync } from "node:fs";
import { gzipSync } from "node:zlib";

const DIR = "dist/client/assets";
const TOP = Number(process.argv[2] ?? 30);

const kB = (bytes: number) => `${(bytes / 1000).toFixed(1)} kB`;

const entry = readdirSync(DIR).find((f) => /^index-.*\.js$/.test(f));
if (!entry) throw new Error(`No entry chunk in ${DIR} — build first.`);

// The static import graph, from the entry.
const critical = new Set<string>();
const pending = [entry];
while (pending.length) {
  const file = pending.pop()!;
  if (critical.has(file)) continue;
  critical.add(file);
  const code = await Bun.file(`${DIR}/${file}`).text();
  for (const m of code.matchAll(
    /(?:^|[;}\n])\s*import\s*(?:[^"'()]*?from\s*)?["']\.\/([^"']+)["']/g,
  )) {
    pending.push(m[1]!);
  }
}

console.log("Loaded before hydration:");
let raw = 0;
let gzip = 0;
for (const file of critical) {
  const bytes = await Bun.file(`${DIR}/${file}`).bytes();
  const zipped = gzipSync(bytes).length;
  raw += bytes.length;
  gzip += zipped;
  console.log(
    `  ${file.padEnd(32)} ${kB(bytes.length).padStart(10)} ${kB(zipped).padStart(10)} gzip`,
  );
}
console.log(
  `  ${"total".padEnd(32)} ${kB(raw).padStart(10)} ${kB(gzip).padStart(10)} gzip\n`,
);

// Attribute every generated byte of the entry chunk to the source its
// sourcemap segment points at (VLQ-decoded by hand).
const code = await Bun.file(`${DIR}/${entry}`).text();
const mapFile = Bun.file(`${DIR}/${entry}.map`);
if (!(await mapFile.exists())) {
  throw new Error("No sourcemap — build with `vite build --sourcemap`.");
}
const map = (await mapFile.json()) as { sources: string[]; mappings: string };
const BASE64 =
  "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const lines = code.split("\n");
const bySource = new Map<string, number>();
let source = 0;
map.mappings.split(";").forEach((line, lineIndex) => {
  const segments: [column: number, source: number | null][] = [];
  let column = 0;
  for (const segment of line.split(",")) {
    if (!segment) continue;
    const values: number[] = [];
    let value = 0;
    let shift = 0;
    for (const char of segment) {
      const digit = BASE64.indexOf(char);
      value += (digit & 31) << shift;
      if (digit & 32) {
        shift += 5;
      } else {
        values.push(value & 1 ? -(value >>> 1) : value >>> 1);
        value = 0;
        shift = 0;
      }
    }
    column += values[0]!;
    if (values.length > 1) source += values[1]!;
    segments.push([column, values.length > 1 ? source : null]);
  }
  const length = lines[lineIndex]?.length ?? 0;
  segments.forEach(([start, src], i) => {
    const end = segments[i + 1]?.[0] ?? length;
    const path = src === null ? "(unmapped)" : map.sources[src]!;
    // Group node_modules by package; keep app sources by path.
    const key =
      path.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1] ??
      path.replace(/^.*?\/src\//, "src/");
    bySource.set(key, (bySource.get(key) ?? 0) + end - start);
  });
});

console.log(`${entry}, by source (raw, top ${TOP}):`);
for (const [key, bytes] of [...bySource]
  .sort((a, b) => b[1] - a[1])
  .slice(0, TOP)) {
  console.log(`  ${kB(bytes).padStart(10)}  ${key}`);
}
